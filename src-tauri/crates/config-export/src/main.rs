//! Explicit host-only exporter. It compiles the production contract sources;
//! it does not load the app, SQLite, credentials or any device resources.

#[cfg(any(target_os = "android", target_os = "ios"))]
compile_error!("vcp-config-export is a host development tool");

#[allow(dead_code)]
#[path = "../../../src/vcp_modules/infra/settings_manager/schema.rs"]
mod schema;
#[allow(dead_code)]
#[path = "../../../src/vcp_modules/infra/settings_manager/types.rs"]
mod types;

use std::path::Path;
use ts_rs::TS;
use types::*;

const HEADER: &str = "// Generated by pnpm config:generate from Rust configuration types and policy.\n// Do not edit by hand. pnpm config:check verifies this file without writing.\n\n";

fn outputs() -> Result<Vec<(&'static str, String)>, String> {
    let config = ts_rs::Config::default();
    let mut declarations = String::from(HEADER);
    macro_rules! emit {
        ($($ty:ty),+ $(,)?) => { $(
            declarations.push_str("export ");
            declarations.push_str(&<$ty>::decl(&config));
            declarations.push_str("\n\n");
        )+ };
    }
    emit!(
        serde_json::Value,
        ChatEndpointMode,
        VoiceInputEncoding,
        VoiceTtsMode,
        VoiceVadSensitivity,
        VoiceVadConfig,
        IdentityConfig,
        ServerConfig,
        LogConfig,
        SyncConfig,
        DistributedConfig,
        ConversationConfig,
        VoiceConnectionConfig,
        VoiceAsrConfig,
        VoiceTtsConfig,
        VoiceGuidanceConfig,
        VoiceConfig,
        JevProvider,
        JevProviderConfig,
        JevConfig,
        NavigationConfig,
        Settings,
        ConfigDomain,
        FieldIssue,
        DomainStatus,
        ConfigSnapshot,
        DomainPatch,
        ConfigUpdate,
        ConfigSaveResult,
        FieldKind,
        ConfigEffect,
        FieldDescriptor,
    );
    let defaults =
        serde_json::to_string_pretty(&Settings::default()).map_err(|error| error.to_string())?;
    let fields: Vec<_> = ConfigDomain::ALL
        .into_iter()
        .flat_map(schema::domain_fields)
        .collect();
    let metadata = serde_json::to_string_pretty(&fields).map_err(|error| error.to_string())?;
    Ok(vec![
        ("config.ts", format!("{}\n", declarations.trim_end())),
        ("defaults.ts", format!("{HEADER}import type {{ Settings }} from './config'\n\nexport const SETTINGS_DEFAULTS: Settings = {defaults}\n")),
        ("metadata.ts", format!("{HEADER}import type {{ FieldDescriptor }} from './config'\n\nexport const SETTINGS_FIELDS: FieldDescriptor[] = {metadata}\n")),
    ])
}

fn run() -> Result<(), String> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = match args.as_slice() {
        [] => false,
        [argument] if argument == "--check" => true,
        _ => return Err("Usage: vcp-config-export [--check]".into()),
    };
    let directory =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/core/config/generated");
    let mut stale = Vec::new();
    for (name, content) in outputs()? {
        let path = directory.join(name);
        let current = match std::fs::read_to_string(&path) {
            Ok(current) => Some(current.replace("\r\n", "\n")),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
            Err(error) => return Err(format!("Cannot read {name}: {error}")),
        };
        if current.as_deref() == Some(content.as_str()) {
            continue;
        }
        if check {
            stale.push(name);
        } else {
            std::fs::create_dir_all(&directory).map_err(|error| error.to_string())?;
            // This tool writes only generated artifacts, never production sources.
            std::fs::write(&path, content).map_err(|error| error.to_string())?;
            println!("Generated {name}");
        }
    }
    if !stale.is_empty() {
        return Err(format!(
            "Configuration contract is stale: {}. Run pnpm config:generate.",
            stale.join(", ")
        ));
    }
    if check {
        println!("Configuration contract is current.");
    }
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("{error}");
        std::process::exit(1);
    }
}
